	// ------------------------------------------------------------------ pass 0: the light settings
	// Luminous Arcana has no plugin of its own. The magic lights below carry the settings its lights
	// were made against - radius, color, flags (inverse square among them), falloff, size, near
	// distance, flicker and fade - and this pass writes them onto the game's own light records when
	// the game has loaded, before anything copies a light. A record whose winning version comes from
	// CS Light.esp already carries these exact values and is left as it is; every other record gets
	// them, whichever plugin changed it last. Generated by lagen.py laplugin.
	struct LightSetting
	{
		const char*   file;
		std::uint32_t localID;
		const char*   editorID;
		std::uint32_t radius;
		int           r, g, b;
		std::uint32_t flags;
		float         falloff, fov, nearDistance, flickerIntensity, flickerMovement, fade;
	};

