	constexpr std::string_view kSameValuesPlugin = "CS Light.esp";

	void LightSettings()
	{
		auto*       dh = RE::TESDataHandler::GetSingleton();
		std::size_t set = 0, missing = 0, renamed = 0, failed = 0, replaced = 0, same = 0;
		for (const auto& s : kLightSettings) {
			auto* light = dh->LookupForm<RE::TESObjectLIGH>(s.localID, s.file);
			if (!light) {
				++missing;
				SKSE::log::warn("[LIGHT-MISSING] {} {:06X} ({}) is not in this load order", s.file, s.localID, s.editorID);
				continue;
			}
			const auto id = EditorID(light);
			if (!id.empty() && Lower(id) != Lower(s.editorID)) {
				++renamed;
				SKSE::log::warn("[LIGHT-RENAMED] {} {:06X} is {} here, expected {}; left alone", s.file, s.localID, id, s.editorID);
				continue;
			}
			// what the load order gave this light, and which plugin gave it - written to the log so a
			// look that differs from the configs can be traced to the record the game actually loaded
			const auto*       owner = light->GetDescriptionOwnerFile();
			const std::string ownerName = owner ? std::string(owner->GetFilename()) : std::string("(unknown)");
			const auto        was = std::format("radius {} | color {},{},{} | flags {:X} | size {} | fade {}", light->data.radius,
				   light->data.color.red, light->data.color.green, light->data.color.blue, light->data.flags.underlying(), light->data.fov,
				   light->fade);
			if (Lower(ownerName) == Lower(kSameValuesPlugin)) {
				++same;
				SKSE::log::info("[LIGHT-KEPT] {} | {} already sets these values", Label(light), ownerName);
				continue;
			}
			if (Lower(ownerName) != Lower(s.file)) {
				++replaced;
				SKSE::log::warn("[LIGHT-REPLACED] {} | {} last changed it ({}); Luminous Arcana's values go over it", Label(light),
					ownerName, was);
			}
			light->data.radius = s.radius;
			light->data.color.red = static_cast<std::uint8_t>(s.r);
			light->data.color.green = static_cast<std::uint8_t>(s.g);
			light->data.color.blue = static_cast<std::uint8_t>(s.b);
			light->data.flags = static_cast<RE::TES_LIGHT_FLAGS>(s.flags);
			light->data.fallofExponent = s.falloff;
			light->data.fov = s.fov;
			light->data.nearDistance = s.nearDistance;
			light->data.flickerIntensityAmplitude = s.flickerIntensity;
			light->data.flickerMovementAmplitude = s.flickerMovement;
			light->fade = s.fade;
			// read back what the game now holds
			if (light->data.radius != s.radius || light->data.flags.underlying() != s.flags || light->fade != s.fade ||
				light->data.fov != s.fov || light->data.color.red != static_cast<std::uint8_t>(s.r)) {
				++failed;
				SKSE::log::warn("[LIGHT-FAILED] {} | the values did not take", Label(light));
				continue;
			}
			++set;
			SKSE::log::info("[LIGHT-SET] {} | radius {} | color {},{},{} | flags {:X} | fade {} | was {}", Label(light), s.radius, s.r,
				s.g, s.b, s.flags, s.fade, was);
		}
		SKSE::log::info("light settings: {} of {} set ({} over another plugin's values), {} already set by {}, {} not in this load "
						"order, {} renamed and left alone, {} failed",
			set, std::size(kLightSettings), replaced, same, kSameValuesPlugin, missing, renamed, failed);
	}
